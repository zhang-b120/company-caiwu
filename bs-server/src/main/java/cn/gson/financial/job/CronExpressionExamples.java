package cn.gson.financial.job;

/**
 * Cron表达式示例和说明
 *
 * 本类提供了详细的Cron表达式格式说明和常用示例
 * 适用于财务系统的定时任务调度
 *
 * 财务系统任务类型：
 * 1. 获取人员信息 - 从外部系统同步员工信息
 * 2. 报个税 - 处理个人所得税申报
 * 3. 获取发票 - 从税务系统获取发票信息
 *
 * @author 开发者
 */
public class CronExpressionExamples {

    /*
     * ======================================================================
     *                            Cron表达式格式
     * ======================================================================
     *
     * 标准格式：秒 分 时 日 月 周 [年]
     *
     * ┌─────────────────── 秒 (0-59)
     * │ ┌───────────────── 分 (0-59)
     * │ │ ┌─────────────── 时 (0-23)
     * │ │ │ ┌───────────── 日 (1-31)
     * │ │ │ │ ┌─────────── 月 (1-12 或 JAN-DEC)
     * │ │ │ │ │ ┌───────── 周 (0-7 或 SUN-SAT，0和7都表示周日)
     * │ │ │ │ │ │ ┌─────── 年 (1970-2099，可选)
     * │ │ │ │ │ │ │
     * * * * * * * *
     */

    /*
     * ======================================================================
     *                             每日定时
     * ======================================================================
     */
    public static final String DAILY_MIDNIGHT = "0 0 0 * * *";           // 每天午夜12:00
    public static final String DAILY_1AM = "0 0 1 * * *";                // 每天凌晨1:00
    public static final String DAILY_2AM = "0 0 2 * * *";                // 每天凌晨2:00
    public static final String DAILY_6AM = "0 0 6 * * *";                // 每天早上6:00
    public static final String DAILY_8AM = "0 0 8 * * *";                // 每天早上8:00
    public static final String DAILY_12PM = "0 0 12 * * *";              // 每天中午12:00
    public static final String DAILY_6PM = "0 0 18 * * *";               // 每天下午6:00
    public static final String DAILY_8PM = "0 0 20 * * *";               // 每天晚上8:00
    public static final String DAILY_11PM = "0 0 23 * * *";              // 每天晚上11:00

    /*
     * ======================================================================
     *                            工作日定时
     * ======================================================================
     */
    public static final String WEEKDAY_8AM = "0 0 8 * * MON-FRI";        // 工作日早上8:00
    public static final String WEEKDAY_9AM = "0 0 9 * * MON-FRI";        // 工作日早上9:00
    public static final String WEEKDAY_12PM = "0 0 12 * * MON-FRI";      // 工作日中午12:00
    public static final String WEEKDAY_6PM = "0 0 18 * * MON-FRI";       // 工作日下午6:00
    public static final String WEEKDAY_MIDNIGHT = "0 0 0 * * MON-FRI";   // 工作日午夜

    /*
     * ======================================================================
     *                            周末定时
     * ======================================================================
     */
    public static final String WEEKEND_9AM = "0 0 9 * * SAT,SUN";        // 周末早上9:00
    public static final String SATURDAY_10AM = "0 0 10 * * SAT";         // 周六早上10:00
    public static final String SUNDAY_8PM = "0 0 20 * * SUN";            // 周日晚上8:00

    /*
     * ======================================================================
     *                            多次执行
     * ======================================================================
     */
    public static final String TWICE_DAILY = "0 0 9,17 * * *";           // 每天9:00和17:00
    public static final String THREE_TIMES_DAILY = "0 0 8,12,18 * * *";  // 每天8:00、12:00、18:00
    public static final String EVERY_4_HOURS = "0 0 */4 * * *";          // 每4小时
    public static final String EVERY_6_HOURS = "0 0 */6 * * *";          // 每6小时
    public static final String EVERY_12_HOURS = "0 0 */12 * * *";        // 每12小时

    /*
     * ======================================================================
     *                            分钟级定时
     * ======================================================================
     */
    public static final String EVERY_MINUTE = "0 * * * * *";             // 每分钟
    public static final String EVERY_5_MINUTES = "0 */5 * * * *";        // 每5分钟
    public static final String EVERY_10_MINUTES = "0 */10 * * * *";      // 每10分钟
    public static final String EVERY_15_MINUTES = "0 */15 * * * *";      // 每15分钟
    public static final String EVERY_30_MINUTES = "0 */30 * * * *";      // 每30分钟
    public static final String TWICE_PER_HOUR = "0 0,30 * * * *";        // 每小时两次(0分和30分)

    /*
     * ======================================================================
     *                            小时级定时
     * ======================================================================
     */
    public static final String EVERY_HOUR = "0 0 * * * *";               // 每小时
    public static final String EVERY_2_HOURS = "0 0 */2 * * *";          // 每2小时
    public static final String EVERY_3_HOURS = "0 0 */3 * * *";          // 每3小时
    public static final String BUSINESS_HOURS = "0 0 9-17 * * MON-FRI";  // 工作日9-17点每小时

    /*
     * ======================================================================
     *                            月度定时
     * ======================================================================
     */
    public static final String MONTHLY_1ST = "0 0 0 1 * *";              // 每月1号午夜
    public static final String MONTHLY_15TH = "0 0 0 15 * *";            // 每月15号午夜
    public static final String MONTHLY_LAST_DAY = "0 0 0 L * *";         // 每月最后一天午夜
    public static final String QUARTERLY = "0 0 0 1 */3 *";              // 每季度第一天(1月、4月、7月、10月)

    /*
     * ======================================================================
     *                            年度定时
     * ======================================================================
     */
    public static final String YEARLY_JAN_1ST = "0 0 0 1 1 *";           // 每年1月1日午夜
    public static final String YEARLY_JUNE_1ST = "0 0 0 1 6 *";          // 每年6月1日午夜
    public static final String YEARLY_DEC_31ST = "0 0 23 31 12 *";       // 每年12月31日晚11点

    /*
     * ======================================================================
     *                            特殊日期
     * ======================================================================
     */
    public static final String FIRST_MONDAY = "0 0 0 1-7 * MON";         // 每月第一个周一
    public static final String LAST_FRIDAY = "0 0 0 * * 5L";            // 每月最后一个周五
    public static final String THIRD_THURSDAY = "0 0 0 * * 4#3";        // 每月第三个周四

    /*
     * ======================================================================
     *                            测试用表达式
     * ======================================================================
     */
    public static final String TEST_EVERY_30_SECONDS = "*/30 * * * * *"; // 每30秒(测试用)
    public static final String TEST_EVERY_MINUTE = "0 * * * * *";        // 每分钟(测试用)
    public static final String TEST_EVERY_2_MINUTES = "0 */2 * * * *";   // 每2分钟(测试用)

    /*
     * ======================================================================
     *                          特殊字符说明
     * ======================================================================
     *
     * *  : 匹配任意值
     *      例：* * * * * * 表示每秒都执行
     *
     * ?  : 不指定值（只能用在日期和星期字段）
     *      例：0 0 0 15 * ? 表示每月15号，不指定星期几
     *
     * -  : 范围分隔符
     *      例：0 0 8-17 * * * 表示每天8点到17点之间每小时执行
     *
     * ,  : 枚举分隔符
     *      例：0 0 8,12,17 * * * 表示每天8点、12点、17点执行
     *
     * /  : 步长分隔符
     *      例：0 *\/15 * * * * 表示每15分钟执行一次
     *      例：0 0/30 * * * * 表示从0分开始，每30分钟执行一次
     *
     * L  : 最后
     *      例：0 0 0 L * * 表示每月最后一天
     *      例：0 0 0 * * 5L 表示每月最后一个周五
     *
     * W  : 工作日（距离指定日期最近的工作日）
     *      例：0 0 0 15W * * 表示每月离15号最近的工作日
     *
     * #  : 第几个星期几
     *      例：0 0 0 * * 5#3 表示每月第3个周五
     *      例：0 0 0 * * 1#1 表示每月第1个周一
     *
     * ======================================================================
     *                          使用建议
     * ======================================================================
     *
     * 1. 生产环境建议使用较低频率的定时任务，避免过度消耗系统资源
     * 2. 测试时可以使用高频率表达式，但上线前务必修改为合适的频率
     * 3. 对于重要的定时任务，建议添加监控和报警机制
     * 4. 考虑服务器时区设置，确保定时任务在正确的时间执行
     * 5. 对于耗时较长的任务，建议使用@Async注解进行异步执行
     *
     * ======================================================================
     *                          常见错误
     * ======================================================================
     *
     * 1. 日期和星期同时指定：应该使用?来表示不指定
     *    错误：0 0 0 15 * MON
     *    正确：0 0 0 15 * ? 或 0 0 0 ? * MON
     *
     * 2. 范围使用错误：
     *    错误：0 0 25-27 * * * (小时范围超出0-23)
     *    正确：0 0 1-3 * * *
     *
     * 3. 步长使用错误：
     *    错误：0 *\/70 * * * * (分钟步长超出0-59范围)
     *    正确：0 *\/30 * * * *
     *
     * ======================================================================
     */
}
